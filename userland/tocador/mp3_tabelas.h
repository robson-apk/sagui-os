/* mp3_tabelas.h - os DADOS que a norma do MP3 traz nos anexos.
 *
 * Um decodificador de MP3 precisa de algumas tabelas que não saem de fórmula
 * nenhuma: foram escolhidas pelos autores do formato (medindo músicas de
 * verdade) e publicadas no Anexo B da norma ISO/IEC 11172-3 (MPEG-1 áudio) e
 * na ISO/IEC 13818-3 (MPEG-2 áudio, as taxas baixas). Todo decodificador do
 * mundo tem os mesmos números; aqui eles estão como dados, e todo o código
 * que os usa está em mp3.c, escrito para o SaguiOS a partir da descrição da
 * norma (D047).
 *
 *   - Tabela 3-B.7: os códigos de Huffman (para cada par de valores, o código
 *     "hcod" e o seu tamanho em bits "hlen");
 *   - Tabela 3-B.8: as faixas de fator de escala (onde cada faixa começa);
 *   - Tabela 3-B.6: a pré-ênfase (pretab);
 *   - Tabela 3-B.3: os 512 coeficientes D[i] da janela de síntese;
 *   - Tabela 3-B.9: os coeficientes c[i] da redução de "alias" (em mp3.c);
 *   - ISO/IEC 13818-3, 2.4.3.2: quantos fatores de escala de cada tamanho
 *     há nas taxas baixas.
 *
 * tests/h86_mp3.py confere se cada tabela de Huffman é um código de prefixo
 * completo (nenhum código é começo de outro e não sobra nem falta nenhum:
 * a soma de 2^-hlen dá exatamente 1), o que pega erro de digitação.
 */
